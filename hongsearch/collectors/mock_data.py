from __future__ import annotations

from hongsearch.models import Comment, Item
from hongsearch.util import days_ago


def _comment(author: str, content: str, likes: int, days: int) -> Comment:
    return Comment(author=author, content=content, like_count=likes, published_at=days_ago(days))


def _item(
    platform: str,
    external_id: str,
    title: str,
    content: str,
    author: str,
    days: int,
    likes: int,
    collects: int,
    comment_count: int,
    shares: int,
    tags: list[str],
    comments: list[Comment],
    source_keyword: str,
) -> Item:
    host = "www.xiaohongshu.com/explore" if platform == "xhs" else "www.douyin.com/video"
    return Item(
        platform=platform,
        external_id=external_id,
        title=title,
        content=content,
        author=author,
        published_at=days_ago(days),
        like_count=likes,
        collect_count=collects,
        comment_count=comment_count,
        share_count=shares,
        url=f"https://{host}/{external_id}",
        tags=["演示样本", *tags],
        comments=comments,
        source_keyword=source_keyword,
    )


